const booleans = [
  'scopeConfirmed',
  'usesOriginal',
  'massProduction',
  'rubbingYuanOrEarlier',
  'originalSuitable',
  'noHardToolBeating',
  'siteSafe',
  'safe',
  'marked',
  'originalUndamaged',
  'physicallyPresent',
  'safeForCustody',
];
export function reproductionValues(value: Record<string, any>, display = false) {
  const out = { ...value };
  for (const key of booleans) {
    const v = out[key];
    out[key] = display ? (v === true ? 'YES' : v === false ? 'NO' : v) : v === 'YES' ? true : v === 'NO' ? false : v;
    if (out[key] === undefined) delete out[key];
  }
  return out;
}
